-- 11. Publish-time validation. Call this from the backend before changing an exam
-- from draft to scheduled/published. It enforces 4 options and exactly 1 correct option.
CREATE OR REPLACE FUNCTION validate_exam_for_publish(p_exam_id UUID)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_question_count INTEGER;
    v_invalid_question_count INTEGER;
    v_access_mode exam_access_mode;
BEGIN
    SELECT access_mode INTO v_access_mode
    FROM exams
    WHERE id = p_exam_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Exam % does not exist', p_exam_id;
    END IF;

    SELECT COUNT(*) INTO v_question_count
    FROM exam_questions
    WHERE exam_id = p_exam_id;

    IF v_question_count = 0 THEN
        RAISE EXCEPTION 'An exam must contain at least one question before publishing';
    END IF;

    SELECT COUNT(*) INTO v_invalid_question_count
    FROM exam_questions eq
    LEFT JOIN LATERAL (
        SELECT COUNT(*) AS option_count,
               COUNT(*) FILTER (WHERE is_correct = TRUE) AS correct_count
        FROM question_version_options qvo
        WHERE qvo.question_version_id = eq.question_version_id
    ) option_stats ON TRUE
    WHERE eq.exam_id = p_exam_id
      AND (option_stats.option_count <> 4 OR option_stats.correct_count <> 1);

    IF v_invalid_question_count > 0 THEN
        RAISE EXCEPTION 'Every question must have exactly four options and exactly one correct option. Invalid questions: %',
            v_invalid_question_count;
    END IF;

    IF v_access_mode = 'assigned' AND NOT EXISTS (
        SELECT 1 FROM exam_assignments WHERE exam_id = p_exam_id
    ) THEN
        RAISE EXCEPTION 'Assign this exam to at least one student before publishing';
    END IF;
END;
$$;

