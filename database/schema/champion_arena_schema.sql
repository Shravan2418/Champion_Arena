-- Champion Arena — PostgreSQL MVP schema
-- User categories: student, admin ONLY.
-- Question format: single-correct multiple-choice (exactly four options, one correct).
-- Question sources: reusable question bank OR exam-specific questions.
--
-- Important security note:
-- The requested MD5 password hash is represented as a 32-character hex field below.
-- MD5 is not suitable for real password storage. Use only for a non-production demo
-- and plan a migration to Argon2id/bcrypt before storing real student credentials.
-- Session tokens are stored as SHA-256 hashes (64 hex characters), not as raw tokens.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE user_role AS ENUM ('student', 'admin');
CREATE TYPE membership_status AS ENUM ('active', 'inactive');
CREATE TYPE question_source AS ENUM ('bank', 'exam_specific');
CREATE TYPE question_difficulty AS ENUM ('easy', 'medium', 'hard');
CREATE TYPE exam_mode AS ENUM ('practice', 'formal');
CREATE TYPE exam_access_mode AS ENUM ('public', 'institution_code', 'assigned');
CREATE TYPE exam_status AS ENUM ('draft', 'scheduled', 'published', 'archived');
CREATE TYPE feedback_timing AS ENUM ('instant', 'after_submit');
CREATE TYPE result_release_mode AS ENUM ('immediately', 'after_exam_end', 'manual');
CREATE TYPE attempt_status AS ENUM ('in_progress', 'submitted', 'auto_submitted', 'abandoned');
CREATE TYPE badge_tier AS ENUM ('bronze', 'silver', 'gold', 'platinum');
CREATE TYPE xp_source AS ENUM ('correct_answer', 'exam_completion', 'practice_streak', 'daily_activity', 'admin_adjustment');

-- 1. Accounts: exactly two application roles.
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash CHAR(32) NOT NULL,
    role user_role NOT NULL DEFAULT 'student',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_users_password_hash_md5_hex
        CHECK (password_hash ~ '^[a-f0-9]{32}$')
);
CREATE UNIQUE INDEX uq_users_email_lower ON users (LOWER(email));
CREATE INDEX idx_users_role_active ON users (role, is_active);

-- Opaque session tokens are generated by the backend; store only their SHA-256 hash.
CREATE TABLE user_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    user_agent TEXT,
    ip_address INET,
    CONSTRAINT ck_user_sessions_token_hash_hex
        CHECK (session_token_hash ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_user_sessions_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_user_sessions_user_active ON user_sessions (user_id, expires_at)
    WHERE revoked_at IS NULL;

-- 2. Institutions: institutions are entities, NOT a third/fourth user role.
-- Students join an institution by submitting its code. Store only a hash of that code.
CREATE TABLE institutions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(180) NOT NULL,
    institution_type VARCHAR(40),
    institution_code_hash CHAR(64) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_institution_code_hash_hex
        CHECK (institution_code_hash ~ '^[a-f0-9]{64}$')
);

CREATE TABLE student_institutions (
    student_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    institution_id UUID NOT NULL REFERENCES institutions(id) ON DELETE CASCADE,
    membership_status membership_status NOT NULL DEFAULT 'active',
    student_identifier VARCHAR(80),
    department VARCHAR(120),
    course_or_program VARCHAR(120),
    academic_year VARCHAR(30),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (student_id, institution_id)
);
CREATE INDEX idx_student_institutions_institution ON student_institutions (institution_id, membership_status);

-- 3. Subjects and topics used to organise question bank items and exams.
CREATE TABLE subjects (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE topics (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_id UUID NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (subject_id, name),
    UNIQUE (id, subject_id)
);

-- 4. Question catalogue.
-- source_type='bank' questions may be reused in many exams.
-- source_type='exam_specific' questions are restricted to one exam by a partial unique index below.
-- Edits create a new question_versions row; published exams keep their selected version.
CREATE TABLE questions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_type question_source NOT NULL,
    subject_id UUID REFERENCES subjects(id) ON DELETE SET NULL,
    topic_id UUID,
    difficulty question_difficulty NOT NULL DEFAULT 'medium',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_questions_topic_subject
        FOREIGN KEY (topic_id, subject_id) REFERENCES topics(id, subject_id),
    UNIQUE (id, source_type)
);
CREATE INDEX idx_questions_bank_filter ON questions (subject_id, topic_id, difficulty)
    WHERE source_type = 'bank' AND is_active = TRUE;

CREATE TABLE question_versions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    question_id UUID NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    question_text TEXT NOT NULL,
    explanation TEXT,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (question_id, version_number),
    UNIQUE (id, question_id)
);
CREATE INDEX idx_question_versions_latest ON question_versions (question_id, version_number DESC);

CREATE TABLE question_version_options (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    question_version_id UUID NOT NULL REFERENCES question_versions(id) ON DELETE CASCADE,
    option_key CHAR(1) NOT NULL CHECK (option_key IN ('A', 'B', 'C', 'D')),
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (question_version_id, option_key),
    UNIQUE (id, question_version_id)
);

-- 5. Exams. 'institution_code' access is granted to active members of the selected institution.
-- 'assigned' access is granted through exam_assignments. 'public' needs no membership/assignment.
CREATE TABLE exams (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title VARCHAR(180) NOT NULL,
    description TEXT,
    subject_id UUID REFERENCES subjects(id) ON DELETE SET NULL,
    exam_mode exam_mode NOT NULL,
    access_mode exam_access_mode NOT NULL DEFAULT 'public',
    institution_id UUID REFERENCES institutions(id) ON DELETE RESTRICT,
    status exam_status NOT NULL DEFAULT 'draft',
    duration_seconds INTEGER NOT NULL CHECK (duration_seconds > 0),
    attempt_limit SMALLINT NOT NULL DEFAULT 1 CHECK (attempt_limit > 0),
    feedback_timing feedback_timing NOT NULL,
    result_release_mode result_release_mode NOT NULL DEFAULT 'immediately',
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    shuffle_questions BOOLEAN NOT NULL DEFAULT FALSE,
    shuffle_options BOOLEAN NOT NULL DEFAULT FALSE,
    show_explanations_after_submit BOOLEAN NOT NULL DEFAULT TRUE,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_exam_feedback_mode CHECK (
        (exam_mode = 'practice' AND feedback_timing = 'instant') OR
        (exam_mode = 'formal' AND feedback_timing = 'after_submit')
    ),
    CONSTRAINT ck_exam_institution_access CHECK (
        (access_mode = 'institution_code' AND institution_id IS NOT NULL) OR
        (access_mode IN ('public', 'assigned') AND institution_id IS NULL)
    ),
    CONSTRAINT ck_exam_schedule CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX idx_exams_status_schedule ON exams (status, starts_at, ends_at);
CREATE INDEX idx_exams_access_institution ON exams (access_mode, institution_id, status);
CREATE INDEX idx_exams_created_by ON exams (created_by, created_at DESC);

-- 6. Questions attached to an exam. The exact question version is frozen for that exam.
CREATE TABLE exam_questions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    exam_id UUID NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    question_id UUID NOT NULL,
    question_version_id UUID NOT NULL,
    source_type question_source NOT NULL,
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    marks NUMERIC(8,2) NOT NULL DEFAULT 1.00 CHECK (marks > 0),
    negative_marks NUMERIC(8,2) NOT NULL DEFAULT 0.00 CHECK (negative_marks >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_exam_questions_source
        FOREIGN KEY (question_id, source_type) REFERENCES questions(id, source_type),
    CONSTRAINT fk_exam_questions_version
        FOREIGN KEY (question_version_id, question_id) REFERENCES question_versions(id, question_id),
    UNIQUE (exam_id, display_order),
    UNIQUE (exam_id, question_id),
    UNIQUE (id, exam_id, question_version_id)
);
CREATE INDEX idx_exam_questions_exam_order ON exam_questions (exam_id, display_order);
-- One exam-specific question cannot be attached to multiple exams.
CREATE UNIQUE INDEX uq_exam_specific_question_single_exam
    ON exam_questions (question_id)
    WHERE source_type = 'exam_specific';

-- 7. Admin assigns an exam to individual students when access_mode='assigned'.
CREATE TABLE exam_assignments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    exam_id UUID NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    student_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assigned_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    due_at TIMESTAMPTZ,
    UNIQUE (exam_id, student_id)
);
CREATE INDEX idx_exam_assignments_student ON exam_assignments (student_id, assigned_at DESC);

-- 8. Attempts and saved answers.
CREATE TABLE exam_attempts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    exam_id UUID NOT NULL REFERENCES exams(id) ON DELETE RESTRICT,
    student_id UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    attempt_number SMALLINT NOT NULL CHECK (attempt_number > 0),
    status attempt_status NOT NULL DEFAULT 'in_progress',
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deadline_at TIMESTAMPTZ NOT NULL,
    submitted_at TIMESTAMPTZ,
    time_spent_seconds INTEGER NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (exam_id, student_id, attempt_number),
    -- Required by student_answers FK (attempt_id, exam_id).
    -- PostgreSQL needs an exact matching UNIQUE key for a composite FK.
    UNIQUE (id, exam_id),
    UNIQUE (id, exam_id, student_id),
    CONSTRAINT ck_attempt_deadline CHECK (deadline_at > started_at),
    CONSTRAINT ck_attempt_submission CHECK (
        (status IN ('in_progress', 'abandoned') AND submitted_at IS NULL) OR
        (status IN ('submitted', 'auto_submitted') AND submitted_at IS NOT NULL)
    )
);
CREATE INDEX idx_attempts_student_recent ON exam_attempts (student_id, started_at DESC);
CREATE INDEX idx_attempts_exam_status ON exam_attempts (exam_id, status);

CREATE TABLE student_answers (
    attempt_id UUID NOT NULL,
    exam_id UUID NOT NULL,
    exam_question_id UUID NOT NULL,
    question_version_id UUID NOT NULL,
    selected_option_id UUID,
    is_correct BOOLEAN,
    marks_awarded NUMERIC(8,2),
    marked_for_review BOOLEAN NOT NULL DEFAULT FALSE,
    answered_at TIMESTAMPTZ,
    last_saved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (attempt_id, exam_question_id),
    CONSTRAINT fk_answers_attempt
        FOREIGN KEY (attempt_id, exam_id) REFERENCES exam_attempts(id, exam_id) ON DELETE CASCADE,
    CONSTRAINT fk_answers_exam_question
        FOREIGN KEY (exam_question_id, exam_id, question_version_id)
        REFERENCES exam_questions(id, exam_id, question_version_id) ON DELETE RESTRICT,
    CONSTRAINT fk_answers_selected_option
        FOREIGN KEY (selected_option_id, question_version_id)
        REFERENCES question_version_options(id, question_version_id) ON DELETE RESTRICT
);
CREATE INDEX idx_student_answers_attempt ON student_answers (attempt_id);

CREATE TABLE exam_results (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    attempt_id UUID NOT NULL UNIQUE,
    exam_id UUID NOT NULL,
    student_id UUID NOT NULL,
    score NUMERIC(10,2) NOT NULL DEFAULT 0,
    maximum_score NUMERIC(10,2) NOT NULL CHECK (maximum_score >= 0),
    percentage NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (percentage >= 0 AND percentage <= 100),
    correct_count INTEGER NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
    incorrect_count INTEGER NOT NULL DEFAULT 0 CHECK (incorrect_count >= 0),
    unanswered_count INTEGER NOT NULL DEFAULT 0 CHECK (unanswered_count >= 0),
    time_taken_seconds INTEGER NOT NULL DEFAULT 0 CHECK (time_taken_seconds >= 0),
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_results_attempt
        FOREIGN KEY (attempt_id, exam_id, student_id)
        REFERENCES exam_attempts(id, exam_id, student_id) ON DELETE CASCADE
);
CREATE INDEX idx_exam_results_exam_score ON exam_results (exam_id, score DESC, evaluated_at);
CREATE INDEX idx_exam_results_student_recent ON exam_results (student_id, evaluated_at DESC);

-- 9. Gamification: XP ledger, current student totals, and badges.
