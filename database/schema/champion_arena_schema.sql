-- Recommended backend rules (enforce in Express services, not only in the UI):
-- * Only role='admin' can create institutions, exams, questions, assignments, badges, and publish exams.
-- * Only role='student' can join institutions, start exams, create attempts, and submit answers.
-- * Public exams are open to active students; institution_code exams require active membership;
--   assigned exams require a matching exam_assignments row.
-- * Do not return is_correct or correct option IDs to the browser during a formal exam.
-- * On submission, evaluate on the server, write exam_results, close the attempt, and award XP once.
-- * Use transactions for exam publishing, answer submission, evaluation, XP ledger and badge awards.
-- * Never trust client-submitted score, correctness, timer, or XP values.
